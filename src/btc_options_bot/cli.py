class OfflineBroker:
    name = "offline"


class NullNotifier:
    def notify(self, *args: Any, **kwargs: Any) -> None:
        return None


def _print_json(value: Any) -> None:
    print(json.dumps(value, indent=2, sort_keys=True, default=str))


def _load_config(args: argparse.Namespace, *, require_credentials: bool = True) -> BotConfig:
    config = BotConfig.from_env(
        env_file=getattr(args, "env_file", ".env"),
        require_credentials=require_credentials,
    )
    mode = getattr(args, "mode", None)
    if mode:
        config = config.with_overrides(mode=mode)
    return config


def _make_broker(config: BotConfig):
    if config.is_paper:
        return PaperBroker(config, DeltaBroker(config))
    return DeltaBroker(config)


def _make_services(config: BotConfig) -> tuple[logging.Logger, StateStore, Notifier, Any, BotEngine]:
    log = configure_logging(config, level="DEBUG" if os.getenv("BOT_DEBUG") else "INFO")
    config.ensure_directories()
    state = StateStore(config.state_db)
    notifier = Notifier(config, event_sink=state.add_event)
    broker = _make_broker(config)
    engine = BotEngine(config, broker, state, notifier)
    return log, state, notifier, broker, engine


def cmd_init(args: argparse.Namespace) -> int:
    target = Path(getattr(args, "env_file", ".env"))
    if target.exists():
        answer = _ask(f"{target} already exists. Overwrite? [y/N] ", "n")
        if answer.lower() not in {"y", "yes"}:
            print("Keeping existing .env")
            return 0

    print("BTC Options Bot setup (press Enter to accept the default)\n")
    mode = _choose("Mode", ["paper", "testnet", "live"], "paper")
    venue = _choose("Delta account venue", ["india", "global"], "india")
    api_key = ""
    api_secret = ""
    if mode in {"testnet", "live"}:
        api_key = _ask("Delta API key: ", "")
        try:
            api_secret = getpass.getpass("Delta API secret (hidden): ")
        except EOFError:
            api_secret = _ask("Delta API secret: ", "")
    capital_mode = _choose(
        "Capital basis",
        ["net_equity", "fixed", "available_balance"],
        "net_equity",
    )
    fixed_capital = ""
    if capital_mode == "fixed":
        fixed_capital = _ask("Fixed capital amount: ", "1000")
    paper_capital = _ask("Paper capital amount: ", "1000") if mode == "paper" else "1000"
    web_token = ""
    if _choose("Enable web controls with a token?", ["no", "yes"], "no") == "yes":
        web_token = _ask("WEB_TOKEN: ", "")

    values = {
        "BOT_MODE": mode,
        "VENUE": venue,
        "DELTA_API_KEY": api_key,
        "DELTA_API_SECRET": api_secret,
        "LIVE_TRADING_CONFIRMATION": LIVE_CONFIRMATION if mode == "live" else "",
        "CAPITAL_MODE": capital_mode,
        "FIXED_CAPITAL": fixed_capital,
        "CAPITAL_ASSET": "USD" if venue == "india" else "USDT",
        "PAPER_CAPITAL": paper_capital,
        "WEB_TOKEN": web_token,
    }
    content = _apply_env_values(ENV_TEMPLATE, values)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    with contextlib.suppress(OSError):
        target.chmod(0o600)
    print(f"\nWrote {target} (permissions 0600 where supported).")
    print("Next: run `make check`, then `make preview`, then `make paper`.")
    return 0


def _ask(prompt: str, default: str) -> str:
    try:
        value = input(prompt).strip()
    except EOFError:
        value = ""
    return value or default


def _choose(label: str, choices: list[str], default: str) -> str:
    while True:
        value = _ask(f"{label} [{'/'.join(choices)}] ({default}): ", default).lower()
        if value in choices:
            return value
        print(f"Please choose one of: {', '.join(choices)}")


def _env_value(value: str) -> str:
    if value == "":
        return ""
    if any(char.isspace() for char in value) or "#" in value or '"' in value:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def _apply_env_values(text: str, values: dict[str, str]) -> str:
    lines = text.splitlines()
    seen: set[str] = set()
    output: list[str] = []
    for line in lines:
        stripped = line.lstrip()
        if stripped.startswith("#") or "=" not in stripped:
            output.append(line)
            continue
        key = stripped.split("=", 1)[0].replace("export", "", 1).strip()
        if key in values:
            output.append(f"{key}={_env_value(values[key])}")
            seen.add(key)
        else:
            output.append(line)
    for key, value in values.items():
        if key not in seen:
            output.append(f"{key}={_env_value(value)}")
    return "\n".join(output).rstrip() + "\n"


def _preview_payload(config: BotConfig, broker: Any, *, include_account: bool) -> dict[str, Any]:
    now = utc_now()
    signal_result = get_signal(broker, config, now=now)
    session = next_entry_session(now, config)
    payload: dict[str, Any] = {
        "generated_at": iso_utc(now),
        "generated_at_ist": now.astimezone(IST).isoformat(),
        "config": config.safe_dict(),
        "exchange": broker.health_check(),
        "signal": {
            "spot_price": decimal_str(signal_result.spot_price),
            "ema21": decimal_str(signal_result.ema21),
            "direction": signal_result.direction,
            "candles_used": signal_result.candles_used,
            "last_closed_candle": iso_utc(signal_result.last_closed_candle_time),
        },
        "session": session.to_dict(),
        "plan": None,
        "warnings": [],
    }
    try:
        result = build_trade_plan(broker, config, session, now=now)
        payload["plan"] = result.plan.to_dict() if result.plan else None
        if result.reason:
            payload["warnings"].append(result.reason)
    except Exception as exc:
        payload["warnings"].append(f"{type(exc).__name__}: {exc}")

    if include_account:
        try:
            wallet = broker.get_wallet_balances()
            positions = broker.get_positions_margined()
            orders = broker.get_active_orders()
            payload["account"] = {
                "net_equity": decimal_str(wallet.net_equity) if wallet.net_equity else None,
                "positions": [
                    {
                        "product_id": position.product_id,
                        "symbol": position.product_symbol,
                        "size": position.size,
                        "entry_price": decimal_str(position.entry_price),
                        "unrealized_pnl": (
                            decimal_str(position.unrealized_pnl)
                            if position.unrealized_pnl is not None
                            else None
                        ),
                    }
                    for position in positions
                ],
                "open_orders": len(orders),
            }
        except Exception as exc:
            payload["warnings"].append(f"account check: {type(exc).__name__}: {exc}")
    return payload


def cmd_check(args: argparse.Namespace) -> int:
    config = _load_config(args)
    _log, state, notifier, broker, _ = _make_services(config)
    try:
        payload = _preview_payload(config, broker, include_account=True)
        state.add_event(
            "INFO",
            "Check completed",
            f"{config.mode} preflight check",
            {"warnings": payload["warnings"]},
        )
        _print_json(payload)
        return 0 if not payload["warnings"] else 2
    finally:
        notifier.close()


def cmd_preview(args: argparse.Namespace) -> int:
    config = _load_config(args)
    _log, _state, notifier, broker, _ = _make_services(config)
    try:
        payload = _preview_payload(config, broker, include_account=False)
        _print_json(payload)
        return 0
    finally:
        notifier.close()


def cmd_run(args: argparse.Namespace) -> int:
    config = _load_config(args)
    if getattr(args, "no_web", False):
        config = config.with_overrides(web_enabled=False)
    if config.is_live:
        print("WARNING: LIVE MODE WILL PLACE REAL ORDERS WITH REAL MONEY.", file=sys.stderr)
    _log, state, notifier, _broker, engine = _make_services(config)
    health: HealthServer | None = None
    stop_event = threading.Event()

    def handle_signal(signum: int, _frame: Any) -> None:
        logger.info("received signal %s; stopping gracefully", signum)
        stop_event.set()

    signal.signal(signal.SIGTERM, handle_signal)
    signal.signal(signal.SIGINT, handle_signal)

    try:
        with SingleInstanceLock(config.lock_file):
            state.set_runtime("pid", os.getpid())
            state.set_runtime("started_at", iso_utc(utc_now()))
            if config.web_enabled:
                try:
                    candidate = HealthServer(config, engine)
                    candidate.start()
                    health = candidate
                except OSError as exc:
                    health = None
                    logger.warning("could not start dashboard: %s", exc)
            engine.run(stop_event)
        return 0
    except RuntimeError as exc:
        logger.error("%s", exc)
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    finally:
        if health is not None:
            health.stop()
        notifier.close()


def cmd_status(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False)
    config.ensure_directories()
    state = StateStore(config.state_db)
    engine = BotEngine(config, OfflineBroker(), state, NullNotifier())  # type: ignore[arg-type]
    _print_json(engine.status())
    return 0


def cmd_account(args: argparse.Namespace) -> int:
    config = _load_config(args)
    _log, _state, notifier, broker, _ = _make_services(config)
    try:
        command = args.account_command
        if command == "balances":
            wallet = broker.get_wallet_balances()
            _print_json(wallet.raw)
        elif command == "positions":
            positions = broker.get_positions_margined()
            _print_json([position.raw for position in positions])
        elif command == "orders":
            orders = broker.get_active_orders()
            _print_json([order.raw for order in orders])
        else:
            raise ValueError(f"unknown account command: {command}")
        return 0
    finally:
        notifier.close()


def cmd_pause(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False)
    config.pause_file.parent.mkdir(parents=True, exist_ok=True)
    config.pause_file.touch()
    print(f"Paused new entries: {config.pause_file}")
    return 0


def cmd_resume(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False)
    config.pause_file.unlink(missing_ok=True)
    config.kill_file.unlink(missing_ok=True)
    state = StateStore(config.state_db)
    state.set_runtime("safety_halt", None)
    print("Pause/kill files cleared. Restart the bot if it had already stopped.")
    return 0


def cmd_stop(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False)
    config.kill_file.parent.mkdir(parents=True, exist_ok=True)
    config.kill_file.touch()
    print(f"Kill switch enabled: {config.kill_file}. Active positions will be closed by the running bot.")
    return 0


def cmd_emergency_close(args: argparse.Namespace) -> int:
    if not args.confirm:
        print("Refusing without --confirm", file=sys.stderr)
        return 2
    config = _load_config(args)
    config.kill_file.parent.mkdir(parents=True, exist_ok=True)
    config.kill_file.touch()
    _log, state, notifier, _broker, engine = _make_services(config)
    try:
        engine.startup_reconcile()
        deadline = time.monotonic() + args.timeout
        while time.monotonic() < deadline:
            active = state.list_active_cycles()
            if not active:
                break
            engine.tick()
            time.sleep(min(1.0, float(config.poll_seconds)))
        active = state.list_active_cycles()
        _print_json({
            "closed": not active,
            "active_cycles": [cycle.to_dict() for cycle in active],
            "recent_events": state.list_events(20),
        })
        return 0 if not active else 1
    finally:
        notifier.close()


def cmd_backup(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False)
    state = StateStore(config.state_db)
    stamp = datetime.now().strftime("%Y%m%dT%H%M%SZ")
    destination = config.data_dir / "backups" / f"state-{stamp}.sqlite3"
    result = state.backup(destination)
    print(result)
    return 0


def cmd_paper_reset(args: argparse.Namespace) -> int:
    config = _load_config(args, require_credentials=False).with_overrides(mode="paper")
    broker = PaperBroker(config, DeltaBroker(config))
    broker.reset()
    print(f"Paper wallet reset to {decimal_str(config.paper_capital)} {config.capital_asset}")
    return 0


def cmd_version(args: argparse.Namespace) -> int:
    print(__version__)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="btc-options-bot",
        description="Production BTC options strategy bot for Delta Exchange",
    )
    parser.add_argument("--env-file", default=".env", help="path to .env configuration")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("init", help="create a secure .env interactively")

    for name, help_text in (
        ("check", "validate config, API, account, EMA, and option selection"),
        ("preview", "show the exact current signal and order plan without placing orders"),
    ):
        command = sub.add_parser(name, help=help_text)
        command.add_argument("--mode", choices=["paper", "testnet", "live"])

    run = sub.add_parser("run", help="run the long-lived trading service")
    run.add_argument("--mode", choices=["paper", "testnet", "live"])
    run.add_argument("--no-web", action="store_true", help="disable the local dashboard")

    sub.add_parser("status", help="show persisted bot state without network calls")

    account = sub.add_parser("account", help="inspect exchange account data")
    account.add_argument(
        "account_command",
        choices=["balances", "positions", "orders"],
    )
    account.add_argument("--mode", choices=["paper", "testnet", "live"])

    sub.add_parser("pause", help="pause new entries; still manage open positions")
    sub.add_parser("resume", help="clear pause/kill files")
    sub.add_parser("stop", help="request graceful kill and close active positions")

    emergency = sub.add_parser("emergency-close", help="close active bot positions now")
    emergency.add_argument("--confirm", action="store_true")
    emergency.add_argument("--timeout", type=int, default=120)
    emergency.add_argument("--mode", choices=["paper", "testnet", "live"])

    sub.add_parser("backup", help="make a consistent SQLite state backup")
    sub.add_parser("paper-reset", help="reset the simulated paper wallet")
    sub.add_parser("version", help="print version")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    commands = {
        "init": cmd_init,
        "check": cmd_check,
        "preview": cmd_preview,
        "run": cmd_run,
        "status": cmd_status,
        "account": cmd_account,
        "pause": cmd_pause,
        "resume": cmd_resume,
        "stop": cmd_stop,
        "emergency-close": cmd_emergency_close,
        "backup": cmd_backup,
        "paper-reset": cmd_paper_reset,
        "version": cmd_version,
    }
    try:
        return int(commands[args.command](args))
    except ConfigError as exc:
        print(f"CONFIG ERROR: {exc}", file=sys.stderr)
        return 2
    except BotError as exc:
        print(f"BOT ERROR: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Interrupted", file=sys.stderr)
        return 130
    except Exception as exc:
        logger.exception("command failed")
        print(f"UNEXPECTED ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
